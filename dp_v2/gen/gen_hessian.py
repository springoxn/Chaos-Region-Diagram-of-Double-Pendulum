"""
Generate the analytic Hessian of the double-pendulum potential energy as MATLAB
code, for the implicit symplectic integrators in dp_v2/core.

Why this file exists
--------------------
The double pendulum in (theta1, theta2) coordinates has a configuration-
dependent mass matrix M(q), so its Hamiltonian

    H = (1/2) p' M(q)^-1 p + V(q)

is NOT separable and the explicit leapfrog / Yoshida family in sp_step.m does
not apply.  The standard symplectic method for a non-separable Hamiltonian is
the implicit midpoint rule, which needs  d(force)/dq = -hess V  both for the
Newton solve that produces the next state AND for the tangent map that produces
the deviation vectors.

A finite-difference Hessian would inject an O(h) error into the tangent flow of
an otherwise second-order symplectic method, degrading the measured Lyapunov
exponents by exactly the amount this whole exercise is trying to remove.  So
the Hessian is generated symbolically, exactly as dp_jacobian.m is.

The potential used here is the one dp_energy.m already implements:

    V = -m1 g L1 cos(th1) - m2 g (L1 cos(th1) + L2 cos(th2))

Note carefully: V depends only on the angles, NOT on the angular velocities.
The velocity-dependent part of the kinetic energy lives entirely in M(q).  That
is what makes the implicit midpoint rule applicable and makes the "force" a
function of q alone.

Output:  dp_v2/core/dp_hessian.m
"""
import os
import numpy as np
import sympy as sp
from sympy.printing.octave import octave_code

th1, th2 = sp.symbols('th1 th2', real=True)
m1, m2, L1, L2, g = sp.symbols('m1 m2 L1 L2 g', real=True)

# ---------------------------------------------------------------- potential
V = -m1 * g * L1 * sp.cos(th1) - m2 * g * (L1 * sp.cos(th1) + L2 * sp.cos(th2))

H = sp.hessian(V, [th1, th2])
print('hessian V =')
sp.pprint(H)

# The Hessian is diagonal -- V is separable.  Assert it rather than assume it,
# so that a future edit to V cannot silently break the structure the generated
# code relies on.
assert sp.simplify(H[0, 1]) == 0, 'off-diagonal Hessian entry is not zero'
assert sp.simplify(H[1, 0]) == 0, 'off-diagonal Hessian entry is not zero'

h11 = sp.simplify(H[0, 0])      # d2V/dth1^2
h22 = sp.simplify(H[1, 1])      # d2V/dth2^2

# ---------------------------------------------------------------- emit MATLAB
lines = []
lines.append('function [H11, H22] = dp_hessian(th1, th2, m1, m2, L1, L2, g)')
lines.append('%% DP_HESSIAN  Analytic Hessian of the double-pendulum potential energy.')
lines.append('%%')
lines.append('%%   [H11, H22] = dp_hessian(th1, th2, m1, m2, L1, L2, g)')
lines.append('%%')
lines.append('%%   Returns the diagonal entries of  hess V  where')
lines.append('%%')
lines.append('%%       V = -m1 g L1 cos(th1) - m2 g (L1 cos(th1) + L2 cos(th2))')
lines.append('%%')
lines.append('%%   GENERATED by dp_v2/gen/gen_hessian.py -- do not edit by hand.')
lines.append('%%')
lines.append('%%   The Hessian is DIAGONAL because this potential is separable; the')
lines.append('%%   generator asserts that, so the two-output signature cannot silently')
lines.append('%%   become wrong if V is ever changed.')
lines.append('%%')
lines.append('%%   The off-diagonal entries are therefore zero and are not returned.')
lines.append('%%   Callers build the 2x2 Hessian as  diag([H11, H22])  when they need')
lines.append('%%   the full matrix, e.g. for the double pendulum''s implicit midpoint')
lines.append('%%   step (dp_implicit_step.m).')
lines.append('')
lines.append('    H11 = %s;' % octave_code(h11))
lines.append('    H22 = %s;' % octave_code(h22))
lines.append('end')

out = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    '..', 'core', 'dp_hessian.m'))
with open(out, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote', out)

# ---------------------------------------------------------------- sanity
src = '\n'.join(lines)
assert 'pow(' not in src, 'octave_code left a pow() call'
for ln in lines:
    if '=' in ln and ln.strip().startswith(('H11', 'H22')):
        assert ln.count('(') == ln.count(')'), 'unbalanced parens: ' + ln
print('syntax sanity OK')

# ------------------------------------------------- verify against numerical
subs0 = {m1: 1.3, m2: 0.7, L1: 1.1, L2: 0.8, g: 9.81}
for (t1v, t2v) in [(0.9, 2.1), (-2.4, 0.35), (0.0, 0.0)]:
    subs = dict(subs0); subs.update({th1: t1v, th2: t2v})
    ana = np.array([float(h11.subs(subs)), float(h22.subs(subs))])

    def Vnum(a, b):
        s = dict(subs0); s.update({th1: a, th2: b})
        return float(V.subs(s))

    eps = 1e-3
    fd = np.array([
        (Vnum(t1v + eps, t2v) - 2 * Vnum(t1v, t2v) + Vnum(t1v - eps, t2v)) / eps ** 2,
        (Vnum(t1v, t2v + eps) - 2 * Vnum(t1v, t2v) + Vnum(t1v, t2v - eps)) / eps ** 2,
    ])
    err = np.abs(ana - fd).max()
    print('point (%+.2f,%+.2f): analytic %s  fd %s  err %.2e'
          % (t1v, t2v, ana, fd, err))
    # Tolerance is set by the second-difference estimator, not by the Hessian:
    # its truncation error is ~ eps^2 * V'''' / 12 and its roundoff error is
    # ~ machine_eps / eps^2.  With eps = 1e-3 those are ~1e-6 and ~1e-10
    # respectively, so 1e-4 is a fair bound.  Using eps = 1e-6 here (the value
    # a first draft used) lets roundoff dominate at ~1e-4 and the check fails
    # for a correct Hessian.
    assert err < 1e-4, 'Hessian mismatch'

print('Hessian verified against central differences.')
