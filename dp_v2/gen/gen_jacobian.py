"""
Generate the analytic Jacobian of the double-pendulum vector field as MATLAB code.

State:  y = [th1, om1, th2, om2]
        th1' = om1
        om1' = a1(y)
        th2' = om2
        om2' = a2(y)

The variational equations need J = d(rhs)/dy (4x4).  We emit the entries as
explicit analytic expressions rather than letting MATLAB difference the field
numerically -- a finite-difference Jacobian injects an O(h) error into the
tangent flow and biases exactly the quantity the Lyapunov exponent measures.

Output:  dp_v2/core/dp_jacobian.m
"""
import os
import re
import sympy as sp
from sympy.printing.octave import octave_code

th1, th2, om1, om2 = sp.symbols('th1 th2 om1 om2', real=True)
m1, m2, L1, L2, g = sp.symbols('m1 m2 L1 L2 g', real=True)

delta = th2 - th1
sd, cd = sp.sin(delta), sp.cos(delta)

den1 = (m1 + m2) * L1 - m2 * L1 * cd ** 2
den2 = (L2 / L1) * den1

num1 = (m2 * L1 * om1 ** 2 * sd * cd + m2 * g * sp.sin(th2) * cd
        + m2 * L2 * om2 ** 2 * sd - (m1 + m2) * g * sp.sin(th1))
num2 = (-m2 * L2 * om2 ** 2 * sd * cd + (m1 + m2) * g * sp.sin(th1) * cd
        - (m1 + m2) * L1 * om1 ** 2 * sd - (m1 + m2) * g * sp.sin(th2))

a1 = num1 / den1
a2 = num2 / den2

vs = [th1, om1, th2, om2]
print('generating Jacobian...')
J = sp.zeros(4, 4)
J[0, 1] = 1          # d(th1')/d(om1)
J[2, 3] = 1          # d(th2')/d(om2)
for j, v in enumerate(vs):
    J[1, j] = sp.simplify(sp.diff(a1, v))
    J[3, j] = sp.simplify(sp.diff(a2, v))

# --- collect the 8 nonzero entries we actually emit -----------------------
targets = [J[1, 0], J[1, 1], J[1, 2], J[1, 3],
           J[3, 0], J[3, 1], J[3, 2], J[3, 3]]
names = ['J21', 'J22', 'J23', 'J24', 'J41', 'J42', 'J43', 'J44']

# common-subexpression elimination keeps the generated code short and fast
repl, reduced = sp.cse(targets, symbols=sp.numbered_symbols('t'), order='none')

lines = []
lines.append('function J = dp_jacobian(th1, om1, th2, om2, m1, m2, L1, L2, g)')
lines.append('%% DP_JACOBIAN  Analytic Jacobian of the double-pendulum vector field.')
lines.append('%%')
lines.append('%%   State y = [th1; om1; th2; om2],  rhs = [om1; a1; om2; a2].')
lines.append('%%   Returns J = d(rhs)/dy as a 4x4 matrix.')
lines.append('%%')
lines.append('%%   GENERATED by dp_v2/gen/gen_jacobian.py -- do not edit by hand.')
lines.append('%%')
lines.append('%%   An ANALYTIC Jacobian is used deliberately.  Differencing the vector')
lines.append('%%   field numerically would inject an O(h) error straight into the tangent')
lines.append('%%   flow, biasing the Lyapunov exponent -- the very quantity we measure.')
lines.append('')
lines.append('    % The common-subexpression block below is machine-generated; all')
lines.append('    % intermediates are scalars, so the element-wise operators that')
lines.append('    % octave_code emits are equivalent to plain scalar operations.')
lines.append('')
if repl:
    lines.append('    % --- common subexpressions ---')
    for sym, expr in repl:
        lines.append('    %s = %s;' % (sym, octave_code(expr)))
    lines.append('')
lines.append('    % --- Jacobian entries ---')
for nm, expr in zip(names, reduced):
    lines.append('    %s = %s;' % (nm, octave_code(expr)))
lines.append('')
lines.append('    J = [ 0,   1,   0,   0;')
lines.append('         J21, J22, J23, J24;')
lines.append('          0,   0,   0,   1;')
lines.append('         J41, J42, J43, J44];')
lines.append('end')

out = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    '..', 'core', 'dp_jacobian.m'))
with open(out, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote', out)

# --- sanity: no pow(), balanced parens ------------------------------------
src = '\n'.join(lines)
assert 'pow(' not in src, 'octave_code left a pow() call'
for ln in lines:
    if '=' in ln and ln.strip().startswith(('J', 't')):
        assert ln.count('(') == ln.count(')'), 'unbalanced parens: ' + ln
print('syntax sanity OK')

# --- verify against numerical differentiation -----------------------------
import numpy as np
subs0 = {m1: 1.3, m2: 0.7, L1: 1.1, L2: 0.8, g: 9.81}
y0 = np.array([0.9, -1.4, 2.1, 0.6])
subs = dict(subs0)
subs.update({th1: y0[0], om1: y0[1], th2: y0[2], om2: y0[3]})
Jnum = np.array(J.subs(subs), dtype=float)


def rhs(yy):
    t1, o1, t2, o2 = yy
    s = dict(subs0)
    s.update({th1: t1, om1: o1, th2: t2, om2: o2})
    return np.array([o1, float(a1.subs(s)), o2, float(a2.subs(s))], dtype=float)


h = 1e-6
Jfd = np.zeros((4, 4))
for k in range(4):
    e = np.zeros(4); e[k] = h
    Jfd[:, k] = (rhs(y0 + e) - rhs(y0 - e)) / (2 * h)
err = np.abs(Jnum - Jfd).max()
print('max |J_analytic - J_fd| = %.3e' % err)
assert err < 1e-7, 'Jacobian mismatch'
print('Jacobian verified.')

# --- a second, independent point (asymmetric, nonzero om) -----------------
subs = dict(subs0); subs.update({th1: -2.4, om1: 3.1, th2: 0.35, om2: -1.9})
y0 = np.array([-2.4, 3.1, 0.35, -1.9])
Jnum = np.array(J.subs(subs), dtype=float)
for k in range(4):
    e = np.zeros(4); e[k] = h
    Jfd[:, k] = (rhs(y0 + e) - rhs(y0 - e)) / (2 * h)
print('second point max err = %.3e' % np.abs(Jnum - Jfd).max())
