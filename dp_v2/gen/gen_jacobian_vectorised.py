"""
Generate a VECTORIZED Jacobian-apply for the double pendulum.

dp_jacobian.m builds a 4x4 matrix for ONE state, which is what the scalar
integrator wants.  A grid sweep wants J*v for N states at once, and forming N
separate 4x4 matrices then multiplying them is the single largest cost in the
sweep.  This generator emits the product directly:

    A = J(y) * v ,   y and v each 4xN

so the four components are written out as explicit array expressions over the
whole row.  No 4x4 matrices are ever formed, and the (expensive) denominator
and its inverse are computed once per row instead of once per stage.

Output:  dp_v2/core/dp_jacobian_apply.m
"""
import os
import re
import sympy as sp
from sympy.printing.octave import octave_code

th1, om1, th2, om2 = sp.symbols('th1 om1 th2 om2', real=True)
v1, v2, v3, v4 = sp.symbols('v1 v2 v3 v4', real=True)
m1, m2, L1, L2, g = sp.symbols('m1 m2 L1 L2 g', real=True)

delta = th2 - th1
sd, cd = sp.sin(delta), sp.cos(delta)
den1 = (m1 + m2) * L1 - m2 * L1 * cd ** 2
den2 = (L2 / L1) * den1

num1 = (m2 * L1 * om1 ** 2 * sd * cd + m2 * g * sp.sin(th2) * cd
        + m2 * L2 * om2 ** 2 * sd - (m1 + m2) * g * sp.sin(th1))
num2 = (-m2 * L2 * om2 ** 2 * sd * cd + (m1 + m2) * g * sp.sin(th1) * cd
        - (m1 + m2) * L1 * om1 ** 2 * sd - (m1 + m2) * g * sp.sin(th2))
a1 = num1 / den1
a2 = num2 / den2

# Jacobian rows:  J[0]=[0,1,0,0], J[2]=[0,0,0,1], rows 1 and 3 are the
# derivatives of the two accelerations.
J = sp.zeros(4, 4)
J[0, 1] = 1
J[2, 3] = 1
for j, v in enumerate([th1, om1, th2, om2]):
    J[1, j] = sp.diff(a1, v)
    J[3, j] = sp.diff(a2, v)

v = sp.Matrix([v1, v2, v3, v4])
prod = J * v
exprs = [sp.simplify(prod[i]) for i in range(4)]

# --- common-subexpression elimination over all four components -------------
repl, reduced = sp.cse(exprs, symbols=sp.numbered_symbols('s'), order='none')

lines = []
lines.append('function A = dp_jacobian_apply(th1, om1, th2, om2, v1, v2, v3, v4, m1, m2, L1, L2, g)')
lines.append('%% DP_JACOBIAN_APPLY  Vectorised product  A = J(y) * v  for many states at once.')
lines.append('%%')
lines.append('%%   All arguments are 1xN row vectors (or scalars).  Returns A, 4xN.')
lines.append('%%')
lines.append('%%   GENERATED by dp_v2/gen/gen_jacobian_vectorised.py -- do not edit by hand.')
lines.append('%%')
lines.append('%%   WHY THIS EXISTS (performance, and it is the dominant cost)')
lines.append('%%   dp_jacobian.m builds a 4x4 matrix for a single state.  A grid sweep')
lines.append('%%   needs J*v for N states simultaneously; forming N matrices and calling')
lines.append('%%   pagemtimes on them is far slower than evaluating the four components')
lines.append('%%   directly.  Here the product is expanded symbolically, so the common')
lines.append('%%   denominator, its inverse and the shared trig terms are computed ONCE')
lines.append('%%   per row rather than once per state per RK4 stage.')
lines.append('%%')
lines.append('%%   The emitted expressions are algebraically identical to dp_jacobian;')
lines.append('%%   dp_v2/tests/test_core.m checks the two agree entry by entry.')
lines.append('')
if repl:
    lines.append('    % --- common subexpressions ---')
    for sym, e in repl:
        lines.append('    %s = %s;' % (sym, octave_code(e)))
    lines.append('')
lines.append('    % --- A = J*v, componentwise ---')
for i, e in enumerate(reduced):
    lines.append('    A%d = %s;' % (i + 1, octave_code(e)))
lines.append('')
lines.append('    A = [A1; A2; A3; A4];')
lines.append('end')

out = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    '..', 'core', 'dp_jacobian_apply.m'))
with open(out, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote', out)

src = '\n'.join(lines)
assert 'pow(' not in src, 'octave_code left a pow() call'
print('syntax sanity OK')

# --- verify against the scalar Jacobian at several random states -----------
import numpy as np
subs0 = {m1: 1.3, m2: 0.7, L1: 1.1, L2: 0.8, g: 9.81}
rng = np.random.default_rng(0)
worst = 0.0
for trial in range(6):
    y = rng.uniform(-3, 3, 4)
    vv = rng.uniform(-1, 1, 4)
    s = dict(subs0)
    s.update({th1: y[0], om1: y[1], th2: y[2], om2: y[3],
              v1: vv[0], v2: vv[1], v3: vv[2], v4: vv[3]})
    got = np.array([float(e.subs(s)) for e in exprs])

    # independent reference: numeric Jacobian times v
    def accel(yy):
        t1, o1, t2, o2 = yy
        ss = dict(subs0); ss.update({th1: t1, om1: o1, th2: t2, om2: o2})
        return np.array([float(a1.subs(ss)), float(a2.subs(ss))])
    Jn = np.zeros((4, 4))
    h = 1e-6
    for k in range(4):
        ep = np.zeros(4); ep[k] = h
        Jn[0, k] = 1.0 if k == 1 else 0.0
        Jn[2, k] = 1.0 if k == 3 else 0.0
        ap = accel(y + ep); am = accel(y - ep)
        Jn[1, k] = (ap[0] - am[0]) / (2 * h)
        Jn[3, k] = (ap[1] - am[1]) / (2 * h)
    ref = Jn @ vv
    err = np.abs(got - ref).max()
    worst = max(worst, err)

print('max |A_generated - J_numeric*v| over 6 random states = %.3e' % worst)
assert worst < 1e-6, 'vectorised Jacobian apply disagrees with the scalar one'
print('verified against numeric Jacobian.')

# --- also confirm the scalar generator and this one agree symbolically -----
Jscalar = sp.zeros(4, 4)
Jscalar[0, 1] = 1
Jscalar[2, 3] = 1
for j, w in enumerate([th1, om1, th2, om2]):
    Jscalar[1, j] = sp.diff(a1, w)
    Jscalar[3, j] = sp.diff(a2, w)
diffs = [sp.simplify(prod[i] - (Jscalar * v)[i]) for i in range(4)]
assert all(d == 0 for d in diffs), 'symbolic mismatch with dp_jacobian'
print('symbolically identical to dp_jacobian. verified.')
